#!/bin/sh
# Tests of querier-gen.uc: the IGMP querier hotplug script it writes.
# Runs against a fake /sys/class/net and fake bridge / ip / nft commands,
# so nothing on this machine is touched. The script it writes is also run
# through shellcheck when that is installed.
#
#   UCODE="ucode -L /path/to/ucode/modules" sh tests/querier/test_querier_gen.sh

set -u
HERE=$(cd "$(dirname "$0")" && pwd)
GEN=$HERE/../../root/usr/share/isp-tester/querier-gen.uc
UCODE=${UCODE:-ucode}
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
FAILS=0

fail() { echo "FAIL $*"; FAILS=$((FAILS + 1)); }
pass() { echo "ok   $*"; }
check() { # name, command...
	n=$1; shift
	if "$@"; then pass "$n"; else fail "$n"; fi
}
has() { grep -qF -- "$2" "$1"; }

# ---- fake system: wan = the port towards the ISP, lan2 = a DSA port
mkdir -p "$T/sys/wan" "$T/sys/lan2" "$T/bin" "$T/var" "$T/etc"
echo 5 > "$T/sys/wan/ifindex"; echo 5 > "$T/sys/wan/iflink"
echo 7 > "$T/sys/lan2/ifindex"; echo 3 > "$T/sys/lan2/iflink"
ln -s ../../devices/virtual/net/br-iptv "$T/sys/wan/master"
ln -s ../../devices/virtual/net/br-iptv "$T/sys/lan2/master"

# bridge -j <args>: answers from $T/pvid (VLAN 236 untagged on wan when 1)
cat > "$T/bin/bridge" <<'EOF'
#!/bin/sh
shift   # -j
case "$*" in
"vlan show vid 236")
	echo '[{"ifname":"wan","vlans":[{"vlan":236}]},{"ifname":"lan2","vlans":[{"vlan":236}]},{"ifname":"br-iptv","vlans":[{"vlan":236}]}]' ;;
"vlan global show dev br-iptv")
	echo '[{"ifname":"br-iptv","vlans":[{"vlan":1},{"vlan":100,"vlanEnd":300}]}]' ;;
"vlan show dev wan")
	if [ "$(cat "$FAKE_DIR/pvid" 2>/dev/null)" = 1 ]; then
		echo '[{"ifname":"wan","vlans":[{"vlan":236,"flags":["PVID","Egress Untagged"]}]}]'
	else
		echo '[{"ifname":"wan","vlans":[{"vlan":236}]}]'
	fi ;;
*) echo '[]' ;;
esac
EOF
# ip -d -j link show dev br-iptv: an ip-full that knows per-VLAN snooping
cat > "$T/bin/ip" <<'EOF'
#!/bin/sh
echo '[{"ifname":"br-iptv","linkinfo":{"info_kind":"bridge","info_data":{"mcast_snooping":1,"mcast_vlan_snooping":0}}}]'
EOF
# nft: no table yet; everything else logged
cat > "$T/bin/nft" <<'EOF'
#!/bin/sh
echo "nft $*" >> "$FAKE_DIR/calls"
[ "$1" = list ] && exit 1
exit 0
EOF
chmod +x "$T/bin/bridge" "$T/bin/ip" "$T/bin/nft"

S=$T/etc/99-iptv-querier
SU=$T/etc/sysupgrade.conf
ORIG=$T/etc/orig/99-iptv-querier.orig

conf() { # mode [others_off]
	printf '{"iptv":{"vlan":236},"querier":{"mode":"%s","igmp_version":2,"others_off":%s}}\n' "$1" "${2:-true}" > "$T/config.json"
}

gen() {
	env FAKE_DIR="$T" PATH="$T/bin:$PATH" \
		ISP_TESTER_CONFIG="$T/config.json" ISP_TESTER_VARDIR="$T/var" ISP_TESTER_RUNDIR="$T/var" \
		ISP_TESTER_SYSNET="$T/sys" ISP_TESTER_BRIDGE="$T/bin/bridge" ISP_TESTER_IP="$T/bin/ip" \
		ISP_TESTER_NFT="$T/bin/nft" ISP_TESTER_QSCRIPT="$S" ISP_TESTER_SYSUPGRADE="$SU" \
		ISP_TESTER_QORIG="$ORIG" $UCODE "$GEN" "$@" >"$T/out" 2>&1
	RC=$?
}

status() { # key: value of the status JSON, crudely
	sed -n "s/.*\"$1\": *\([^,}]*\).*/\1/p" "$T/var/querier-script.json"
}

# ---- unmanaged: nothing written
conf unmanaged
gen
check "unmanaged exits 0" [ "$RC" = 0 ]
check "unmanaged writes no script" [ ! -e "$S" ]

# ---- the user's own script is kept before it is replaced
printf '#!/bin/sh\n# my own querier\n' > "$S"
conf router
gen
check "router exits 0 ($(cat "$T/out"))" [ "$RC" = 0 ]
check "own script backed up" has "$ORIG" "# my own querier"
check "script written" has "$S" "# generated by luci-app-isp-tester"
check "MODE router" has "$S" "MODE='router'"
check "bridge found via master link" has "$S" "BR='br-iptv'"
check "upstream is the non-DSA port" has "$S" "UP='wan'"
check "VID" has "$S" "VID='236'"
check "other VLANs with 236 cut out" has "$S" "OTHERS='1 100-235 237-300'"
check "tagged filter rule" has "$S" 'vlan id $VID @ll,216,8 2 @ll,272,32 0xe0000001 counter drop'
check "no untagged rule without PVID" sh -c "! grep -q 'untagged\"' '$S'"
check "status: written" [ "$(status written)" = true ]
check "status: applied" [ "$(status applied)" = true ]
check "in sysupgrade.conf" [ "$(grep -cxF "$S" "$SU")" = 1 ]

if command -v shellcheck >/dev/null 2>&1; then
	check "generated script passes shellcheck" shellcheck -s sh -S warning "$S"
else
	echo "skip shellcheck (not installed)"
fi

# ---- the same settings again: no flash write, sysupgrade.conf not doubled
cp "$S" "$T/before"
gen
check "second run: not rewritten" [ "$(status written)" = false ]
check "second run: same file" cmp -s "$S" "$T/before"
check "second run: sysupgrade.conf once" [ "$(grep -cxF "$S" "$SU")" = 1 ]
check "backup not overwritten by ours" has "$ORIG" "# my own querier"

# ---- PVID on the upstream port: the untagged frames are filtered too
echo 1 > "$T/pvid"
gen
check "untagged rule with PVID" has "$S" "isp-tester-q \$UP/\$VID/untagged"
check "untagged own-query rule" has "$S" "isp-tester-o \$UP/\$VID/out/untagged"
rm -f "$T/pvid"

# ---- others_off false: no VLAN list
conf backup false
gen
check "backup mode" has "$S" "MODE='backup'"
check "others_off false: empty list" has "$S" "OTHERS=''"

# ---- off: the script stays, switched off
conf off
gen
check "off keeps the script" has "$S" "MODE='off'"
check "off: script exits at once" sh -c "ACTION=ifup sh '$S' apply; [ \$? = 0 ]"

# ---- an unknown mode is treated as unmanaged
conf bogus
cp "$S" "$T/before"
gen
check "bogus mode leaves the script" cmp -s "$S" "$T/before"

# ---- the busybox ip (no bridge options) is said plainly
conf router
printf '#!/bin/sh\necho "BusyBox: ip: invalid option"\n' > "$T/bin/ip"
gen
check "no ip-full reported" [ "$(status err)" = '"no_ip_full"' ]
check "no ip-full: exit 1" [ "$RC" = 1 ]

echo
if [ "$FAILS" -ne 0 ]; then echo "test_querier_gen: $FAILS failed"; exit 1; fi
echo "test_querier_gen: all passed"
